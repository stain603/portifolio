export const NavbarButton = ({
  href,
  as: Tag = "a",
  children,
  className,
  variant = "primary",
  ...props
}: {
  href?: string;
  as?: React.ElementType;
  children: React.ReactNode;
  className?: string;
  variant?: "primary" | "secondary" | "dark" | "gradient";
} & (
  | React.ComponentPropsWithoutRef<"a">
  | React.ComponentPropsWithoutRef<"button">
)) => {
  const baseStyles =
    "px-4 py-2 rounded-md text-sm font-bold relative cursor-pointer hover:-translate-y-0.5 transition duration-200 inline-block text-center";

  const variantStyles = {
    primary:
      "bg-[#22C55E] text-[#09090B] shadow-[0_0_20px_rgba(74,222,128,0.35)] hover:bg-[#16A34A]",
    secondary:
      "bg-transparent border border-[#27272A] text-[#FAFAFA] shadow-none hover:border-[#22C55E] hover:text-[#4ADE80]",
    dark: "bg-[#18181B] text-[#FAFAFA] border border-[#27272A]",
    gradient: "bg-[#22C55E] text-[#09090B]",
  };

  return (
    <Tag
      href={href || undefined}
      className={cn(baseStyles, variantStyles[variant], className)}
      {...props}
    >
      {children}
    </Tag>
  );
};
