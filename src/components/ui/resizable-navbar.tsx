export const NavItems = ({ items, className, onItemClick }: NavItemsProps) => {
  const [hovered, setHovered] = useState<number | null>(null);
  const [active, setActive] = useState(0);

  useEffect(() => {
    const sectionIds = items.map((item) => item.link.replace("#", ""));

    const observer = new IntersectionObserver(
      (entries) => {
        const visible = entries
          .filter((entry) => entry.isIntersecting)
          .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];

        if (!visible) return;

        const index = sectionIds.indexOf(visible.target.id);
        if (index >= 0) setActive(index);
      },
      { rootMargin: "-45% 0px -45% 0px", threshold: [0, 0.2, 0.5, 0.8] },
    );

    sectionIds.forEach((id) => {
      const element = document.getElementById(id);
      if (element) observer.observe(element);
    });

    return () => observer.disconnect();
  }, [items]);

  const underlineIndex = hovered ?? active;

  return (
    <motion.div
      onMouseLeave={() => setHovered(null)}
      className={cn(
        "absolute inset-0 hidden flex-1 flex-row items-center justify-center space-x-2 text-sm font-medium lg:flex lg:space-x-2",
        className,
      )}
    >
      {items.map((item, idx) => (
        <a
          onMouseEnter={() => setHovered(idx)}
          onClick={() => {
            setActive(idx);
            onItemClick?.();
          }}
          className={cn(
            "relative px-4 py-2 transition-colors",
            underlineIndex === idx ? "text-[#FAFAFA]" : "text-[#A1A1AA] hover:text-[#FAFAFA]",
          )}
          key={`link-${idx}`}
          href={item.link}
        >
          <span className="relative z-10">{item.name}</span>
          {underlineIndex === idx && (
            <motion.span
              layoutId="navbar-underline"
              className="absolute inset-x-2 bottom-1 h-0.5 rounded-full bg-[#22C55E]"
              transition={{ type: "spring", stiffness: 420, damping: 32 }}
            />
          )}
        </a>
      ))}
    </motion.div>
  );
};

